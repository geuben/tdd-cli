"""`tdd init --skill`: the driving skill and hooks, from the copies installed with the binary."""

from __future__ import annotations

import json
import subprocess
import tomllib
from pathlib import Path

import pytest
import yaml

from conftest import run_cli
from tddcli import contract, docs
from tddcli.envelope import ENVELOPE_VERSION, VERB_SET_VERSION

REPO_ROOT = Path(__file__).resolve().parents[1]
SKILL = ".claude/skills/tdd-drive/SKILL.md"
STOP_HOOK = ".claude/hooks/tdd_stop_hook.py"
BASH_HOOK = ".claude/hooks/tdd_bash_hook.py"
SETTINGS = ".claude/settings.json"
EXPECTED_SETTINGS = {
    "hooks": {
        "Stop": [
            {
                "hooks": [
                    {
                        "type": "command",
                        "command": 'python3 "$CLAUDE_PROJECT_DIR/.claude/hooks/tdd_stop_hook.py"',
                    }
                ]
            }
        ],
        "PreToolUse": [
            {
                "matcher": "Bash",
                "hooks": [
                    {
                        "type": "command",
                        "command": 'python3 "$CLAUDE_PROJECT_DIR/.claude/hooks/tdd_bash_hook.py"',
                    }
                ],
            }
        ],
    }
}


@pytest.fixture
def bare_repo(tmp_path, ledger_home):
    root = tmp_path / "workspace"
    root.mkdir()
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    return root


@pytest.fixture
def packaged(tmp_path, monkeypatch):
    """A fake installed `_docs`: what init must copy from, not the checkout."""
    files = {
        "examples/skills/tdd-drive/SKILL.md": "packaged skill\n",
        "examples/claude-code-hooks/stop_hook.py": "packaged stop\n",
        "examples/claude-code-hooks/bash_hook.py": "packaged bash\n",
    }
    root = tmp_path / "_docs"
    for rel, text in files.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text)
    monkeypatch.setattr(docs, "_PACKAGED", root)
    return files


def read(repo: Path, rel: str) -> str | None:
    path = repo / rel
    return path.read_text() if path.is_file() else None


def test_the_shipped_skill_declares_the_versions_this_binary_emits():
    text = (REPO_ROOT / "examples/skills/tdd-drive/SKILL.md").read_text()
    front = yaml.safe_load(contract.split_front_matter(text))
    assert front.get("metadata") == {
        "verb_set_version": str(VERB_SET_VERSION),
        "envelope_version": str(ENVELOPE_VERSION),
    }


def test_init_skill_writes_the_installed_driving_skill(bare_repo, packaged):
    run_cli(bare_repo, "init", "--skill", "claude-code")
    assert read(bare_repo, SKILL) == "packaged skill\n"


def test_an_unknown_harness_is_refused_and_nothing_is_written(bare_repo):
    out = run_cli(bare_repo, "init", "--skill", "cursor")
    assert (
        out["ok"],
        out["result"].get("reason"),
        "claude-code" in out.get("error", ""),
        (bare_repo / "tdd.toml").exists(),
    ) == (False, "unknown_harness", True, False)


def test_init_skill_writes_the_installed_hooks(bare_repo, packaged):
    run_cli(bare_repo, "init", "--skill", "claude-code")
    assert {STOP_HOOK: read(bare_repo, STOP_HOOK), BASH_HOOK: read(bare_repo, BASH_HOOK)} == {
        STOP_HOOK: "packaged stop\n",
        BASH_HOOK: "packaged bash\n",
    }


def test_every_scaffolded_file_is_carried_into_the_wheel():
    from tddcli import harness

    pyproject = tomllib.loads((REPO_ROOT / "pyproject.toml").read_text())
    included = pyproject["tool"]["hatch"]["build"]["targets"]["wheel"]["force-include"]
    sources = [f.source for h in harness.HARNESSES.values() for f in h.files]
    assert {s: included.get(s) for s in sources} == {s: f"tddcli/_docs/{s}" for s in sources}


def test_a_scaffold_missing_from_the_install_is_refused_and_nothing_is_written(
    bare_repo, monkeypatch
):
    monkeypatch.setattr(docs, "_PACKAGED", Path("/nonexistent"))
    monkeypatch.setattr(docs, "_SOURCE", Path("/nonexistent"))
    out = run_cli(bare_repo, "init", "--skill", "claude-code")
    assert (
        out["ok"],
        out["result"].get("reason"),
        (bare_repo / "tdd.toml").exists(),
        read(bare_repo, SKILL),
    ) == (False, "missing_from_install", False, None)


def test_init_skill_keeps_an_existing_tdd_toml_unless_forced(bare_repo, packaged):
    (bare_repo / "tdd.toml").write_text("# mine\n")
    kept = run_cli(bare_repo, "init", "--skill", "claude-code")
    kept_text = read(bare_repo, "tdd.toml")
    run_cli(bare_repo, "init", "--skill", "claude-code", "--force")
    assert (
        kept["ok"],
        kept_text,
        kept["result"].get("config"),
        read(bare_repo, "tdd.toml").startswith("# Generated by `tdd init`"),
    ) == (True, "# mine\n", "kept", True)


def test_init_skill_writes_settings_that_wire_both_hooks(bare_repo, packaged):
    out = run_cli(bare_repo, "init", "--skill", "claude-code")
    assert (
        json.loads(read(bare_repo, SETTINGS) or "null"),
        out["result"].get("harness", {}).get("settings"),
    ) == (EXPECTED_SETTINGS, "written")


def test_an_existing_settings_file_is_left_alone_and_the_stanza_handed_over(
    tmp_path, ledger_home, packaged
):
    seen = []
    for i, original in enumerate(('{"permissions": {"allow": ["Bash(ls:*)"]}}\n', "{not json\n")):
        repo = tmp_path / f"ws{i}"
        repo.mkdir()
        subprocess.run(["git", "init", "-q", str(repo)], check=True)
        (repo / ".claude").mkdir()
        (repo / SETTINGS).write_text(original)
        out = run_cli(repo, "init", "--skill", "claude-code")
        h = out["result"].get("harness", {})
        seen.append(
            (
                read(repo, SETTINGS) == original,
                h.get("settings"),
                h.get("settings_stanza"),
                "settings_stanza" in out["next_action"]["detail"],
            )
        )
    assert seen == [(True, "not_written", EXPECTED_SETTINGS, True)] * 2


def test_settings_that_already_wire_both_hooks_are_reported_as_wired(bare_repo, packaged):
    run_cli(bare_repo, "init", "--skill", "claude-code")
    out = run_cli(bare_repo, "init", "--skill", "claude-code")
    assert (
        out["result"]["harness"]["settings"],
        "settings_stanza" in out["next_action"]["detail"],
    ) == ("wired", False)


def test_a_harness_file_that_differs_is_refused_with_or_without_force(bare_repo, packaged):
    (bare_repo / SKILL).parent.mkdir(parents=True)
    (bare_repo / SKILL).write_text("my skill\n")
    plain = run_cli(bare_repo, "init", "--skill", "claude-code")
    forced = run_cli(bare_repo, "init", "--skill", "claude-code", "--force")
    assert (
        [(o["ok"], o["result"].get("reason"), o["result"].get("differs")) for o in (plain, forced)],
        read(bare_repo, SKILL),
        (bare_repo / "tdd.toml").exists(),
    ) == ([(False, "harness_files_differ", [SKILL])] * 2, "my skill\n", False)


def test_update_skill_replaces_a_harness_file_that_differs(bare_repo, packaged):
    (bare_repo / SKILL).parent.mkdir(parents=True)
    (bare_repo / SKILL).write_text("my skill\n")
    out = run_cli(bare_repo, "init", "--skill", "claude-code", "--update-skill")
    assert (out["ok"], read(bare_repo, SKILL)) == (True, "packaged skill\n")
