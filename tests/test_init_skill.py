def test_init_skill_keeps_an_existing_tdd_toml_unless_forced(bare_repo, packaged):
    (bare_repo / "tdd.toml").write_text("# mine\n")
    kept = run_cli(bare_repo, "init", "--skill", "claude-code")
    kept_text = read(bare_repo, "tdd.toml")
    run_cli(bare_repo, "init", "--skill", "claude-code", "--force")
    assert (
        kept["ok"],
        kept_text,
        kept["result"].get("config"),
        read(bare_repo, "tdd.toml").startswith("# Generated by `tdd init`"),
    ) == (True, "# mine\n", "kept", True)


